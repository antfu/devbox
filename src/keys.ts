import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import process from 'node:process'
import { ROOT } from './shell'

/** The GitHub accounts the paseo servers act as, and the .env variables that name each one. */
export const IDENTITIES = {
  bot: { name: 'GIT_NAME_BOT', email: 'GIT_EMAIL_BOT' },
  main: { name: 'GIT_NAME_MAIN', email: 'GIT_EMAIL_MAIN' },
} as const

export type IdentityId = keyof typeof IDENTITIES

export function isIdentityId(id: string): id is IdentityId {
  return id in IDENTITIES
}

/** Where the containers mount keys/gpg/<id>; the gitconfig written here has to name the same path. */
const MOUNT = '/etc/signing'

/**
 * Generate the GPG key one identity's agents sign commits and tags with, and write it to keys/gpg/<id>:
 * `private.asc`, `public.asc` and a `gitconfig` that names the key. The key has no passphrase and no
 * expiry, and is made in a throwaway keyring so the host's own keys are never touched.
 */
export function setupGpgKey(id: IdentityId, force = false): void {
  const dir = join(ROOT, 'keys/gpg', id)
  if (existsSync(join(dir, 'private.asc')) && !force)
    throw new Error(`keys/gpg/${id} already holds a key; pass --force to replace it`)

  try {
    process.loadEnvFile('.env')
  }
  catch {
    // .env is optional, the variables may come from the shell.
  }
  const vars = IDENTITIES[id]
  const name = process.env[vars.name]
  const email = process.env[vars.email]
  // GitHub only verifies a signature whose key has the account's email, so a made-up one is no use.
  if (!name || !email)
    throw new Error(`set ${vars.name} and ${vars.email} in .env, the identity the ${id} key is for`)

  // A short path, since gpg-agent's socket path has a hard length limit.
  const home = mkdtempSync('/tmp/gpg-')
  const gpg = (...args: string[]): string => execFileSync('gpg', ['--homedir', home, '--batch', ...args], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
  })

  try {
    gpg(
      '--pinentry-mode',
      'loopback',
      '--passphrase',
      '',
      '--quick-generate-key',
      `${name} (agent signing) <${email}>`,
      'ed25519',
      'sign',
      'never',
    )
    const fingerprint = gpg('--list-secret-keys', '--with-colons')
      .split('\n')
      .find(line => line.startsWith('fpr:'))
      ?.split(':')[9]
    if (!fingerprint)
      throw new Error('gpg did not report a fingerprint')

    mkdirSync(dir, { recursive: true })
    // Readable by the containers' user through the read-only mount; the folder is the access boundary.
    writeFileSync(join(dir, 'private.asc'), gpg('--pinentry-mode', 'loopback', '--passphrase', '', '--export-secret-keys', '--armor', fingerprint))
    const publicKey = gpg('--export', '--armor', fingerprint)
    writeFileSync(join(dir, 'public.asc'), publicKey)
    writeFileSync(join(dir, 'gitconfig'), gitconfig(fingerprint))

    console.log(`Wrote keys/gpg/${id} for ${fingerprint}`)
    console.log(`Add this public key to the GitHub account of ${email} at https://github.com/settings/gpg/new:\n`)
    console.log(publicKey)
  }
  finally {
    // Stop the agent first, or it recreates its socket in the folder being removed.
    try {
      execFileSync('gpgconf', ['--homedir', home, '--kill', 'all'], { stdio: 'ignore' })
    }
    catch {
      // No agent was started.
    }
    rmSync(home, { recursive: true, force: true })
  }
}

function gitconfig(fingerprint: string): string {
  return `# Read by git as the system config inside the container (GIT_CONFIG_SYSTEM).
# Generated by \`pnpm keys:setup\`; ${MOUNT}/private.asc is imported on start.
[user]
\tsigningkey = ${fingerprint}
[commit]
\tgpgsign = true
[tag]
\tgpgsign = true
`
}
