import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import process from 'node:process'
import { ROOT } from './shell'

const GPG_DIR = join(ROOT, 'keys/gpg')

/** Where paseo mounts GPG_DIR; the gitconfig written here has to name the same path. */
const MOUNT = '/etc/paseo-keys/gpg'

/**
 * Generate the GPG key paseo's agents sign commits and tags with, and write it to keys/gpg:
 * `private.asc`, `public.asc` and a `gitconfig` that names the key. The key has no passphrase and no
 * expiry, and is made in a throwaway keyring so the host's own keys are never touched.
 */
export function setupGpgKey(force = false): void {
  if (existsSync(join(GPG_DIR, 'private.asc')) && !force)
    throw new Error('keys/gpg already holds a key; pass --force to replace it')

  try {
    process.loadEnvFile('.env')
  }
  catch {
    // .env is optional, the defaults below apply.
  }
  const name = process.env.GIT_NAME || 'paseo'
  const email = process.env.GIT_EMAIL || 'paseo@localhost'

  // A short path, since gpg-agent's socket path has a hard length limit.
  const home = mkdtempSync('/tmp/gpg-')
  const gpg = (...args: string[]): string => execFileSync('gpg', ['--homedir', home, '--batch', ...args], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
  })

  try {
    gpg(
      '--pinentry-mode',
      'loopback',
      '--passphrase',
      '',
      '--quick-generate-key',
      `${name} (paseo signing) <${email}>`,
      'ed25519',
      'sign',
      'never',
    )
    const fingerprint = gpg('--list-secret-keys', '--with-colons')
      .split('\n')
      .find(line => line.startsWith('fpr:'))
      ?.split(':')[9]
    if (!fingerprint)
      throw new Error('gpg did not report a fingerprint')

    mkdirSync(GPG_DIR, { recursive: true })
    // Readable by the paseo user through the read-only mount; the folder is the access boundary.
    writeFileSync(join(GPG_DIR, 'private.asc'), gpg('--pinentry-mode', 'loopback', '--passphrase', '', '--export-secret-keys', '--armor', fingerprint))
    const publicKey = gpg('--export', '--armor', fingerprint)
    writeFileSync(join(GPG_DIR, 'public.asc'), publicKey)
    writeFileSync(join(GPG_DIR, 'gitconfig'), gitconfig(fingerprint))

    console.log(`Wrote keys/gpg for ${fingerprint}`)
    console.log('Add this public key to GitHub at https://github.com/settings/gpg/new:\n')
    console.log(publicKey)
  }
  finally {
    // Stop the agent first, or it recreates its socket in the folder being removed.
    try {
      execFileSync('gpgconf', ['--homedir', home, '--kill', 'all'], { stdio: 'ignore' })
    }
    catch {
      // No agent was started.
    }
    rmSync(home, { recursive: true, force: true })
  }
}

function gitconfig(fingerprint: string): string {
  return `# Read by git as the system config inside the paseo container (GIT_CONFIG_SYSTEM).
# Generated by \`pnpm keys:setup\`; ${MOUNT}/private.asc is imported on start.
[user]
\tsigningkey = ${fingerprint}
[commit]
\tgpgsign = true
[tag]
\tgpgsign = true
`
}
